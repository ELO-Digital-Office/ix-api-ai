#!/usr/bin/env python3
"""Generate Markdown references from an Indexserver OpenAPI definition.

Usage:
    scripts/generate-api-docs.py [api/<version>] [--check]

Without a version directory, every directory below api/ is processed.
Writes <version>/generated/operations.md and <version>/generated/schemas.md.
With --check, nothing is written; the exit code is 1 if a file is outdated.
"""

import argparse
import html
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUEST_PREFIX = "BRequest_"
RESULT_PREFIX = "BResult_"
SUMMARY_LEN = 160
PROPERTY_DESC_LEN = 200
AGENT_NOTE = (
    "Generated by `scripts/generate-api-docs.py` from `openapi.json`. Do not edit.\n"
    "For task-oriented guidance, read `skills/elo-indexserver-rest/SKILL.md` and `knowledge/` first."
)


def clean(text):
    """Strip HTML and Javadoc markup and collapse whitespace."""
    if not text:
        return ""
    text = re.sub(r"\{@(?:link|linkplain|code)\s+([^}]*)\}", r"`\1`", text)
    text = re.sub(r"<code>(.*?)</code>", r"`\1`", text, flags=re.S)
    text = re.sub(r"<[^>]+>", " ", text)
    text = html.unescape(text)
    text = re.sub(r"\s+/\s*$", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text.replace("|", "\\|")


def shorten(text, limit):
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0]
    # Do not leave an unbalanced inline code span behind.
    if cut.count("`") % 2:
        cut = cut[: cut.rfind("`")].rstrip()
    return cut + " …"


def first_sentence(text):
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return match.group(1) if match else text


def ref_name(ref):
    return ref.rsplit("/", 1)[-1]


def type_of(schema):
    if not schema:
        return ""
    if "$ref" in schema:
        return ref_name(schema["$ref"])
    if "allOf" in schema:
        return " & ".join(type_of(s) for s in schema["allOf"])
    t = schema.get("type", "object")
    if t == "array":
        return type_of(schema.get("items")) + "[]"
    if t == "object" and isinstance(schema.get("additionalProperties"), dict):
        return "map<string, " + type_of(schema["additionalProperties"]) + ">"
    if schema.get("format") == "binary":
        return "binary"
    if "format" in schema and t in ("integer", "number"):
        return schema["format"]
    return t


def operation_rows(spec):
    schemas = spec["components"]["schemas"]
    by_tag = defaultdict(list)
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in ("get", "post", "put", "delete", "patch"):
                continue
            tag = (op.get("tags") or [path.strip("/").split("/")[0]])[0]

            params = []
            for content_type, content in op.get("requestBody", {}).get("content", {}).items():
                body = content.get("schema", {})
                if "$ref" in body:
                    props = schemas.get(ref_name(body["$ref"]), {}).get("properties", {})
                    params += [f"`{n}`: {type_of(s)}" for n, s in props.items() if n != "ci"]
                else:
                    params.append(f"body ({content_type}): {type_of(body)}")

            returns = ""
            ok = op.get("responses", {}).get("200", {}).get("content", {})
            for content in ok.values():
                body = content.get("schema", {})
                if "$ref" in body:
                    result = schemas.get(ref_name(body["$ref"]), {}).get("properties", {}).get("result")
                    returns = type_of(result) if result else "void"
                else:
                    returns = type_of(body)

            summary = clean(" ".join(x for x in (item.get("summary"), item.get("description")) if x))
            summary = shorten(first_sentence(summary), SUMMARY_LEN)
            by_tag[tag].append((method.upper(), path, ", ".join(params), returns, summary))
    return by_tag


def render_operations(spec):
    info = spec["info"]
    by_tag = operation_rows(spec)
    total = sum(len(rows) for rows in by_tag.values())
    out = [
        f"# {info['title']} REST API Operations",
        "",
        f"**Version:** {info['version']}  ",
        f"**OpenAPI:** {spec.get('openapi', '')}",
        "",
        AGENT_NOTE,
        "",
        "## Servers",
        "",
    ]
    for server in spec.get("servers", []):
        out.append(f"- `{server['url']}` — {server.get('description', '')}")
    out += ["", "## Authentication", ""]
    for name, scheme in spec["components"].get("securitySchemes", {}).items():
        details = ", ".join(f"{k}=`{v}`" for k, v in scheme.items())
        out.append(f"- **{name}**: {details}")
    out += [
        "",
        "## Calling convention",
        "",
        "Every operation is a POST to `<server>/<Interface>/<function>` with a JSON object",
        "containing the listed parameters. The `ci` (ClientInfo) parameter is omitted below",
        "because it is optional. The response is `{\"result\": <Returns>}` on success or",
        "`{\"exception\": \"...[ELOIX:code]...\"}` on failure.",
        "",
        f"## Interfaces ({total} operations)",
        "",
    ]
    for tag in sorted(by_tag):
        out.append(f"- [{tag}](#{tag.lower()}) ({len(by_tag[tag])})")
    for tag in sorted(by_tag):
        out += ["", f"## {tag}", "", "| Path | Parameters | Returns | Summary |", "|------|------------|---------|---------|"]
        for method, path, params, returns, summary in sorted(by_tag[tag], key=lambda r: r[1]):
            prefix = "" if method == "POST" else f"{method} "
            out.append(f"| {prefix}`{path}` | {params} | {returns} | {summary} |")
    return "\n".join(out) + "\n"


def render_schemas(spec):
    info = spec["info"]
    schemas = spec["components"]["schemas"]
    models = sorted(n for n in schemas if not n.startswith((REQUEST_PREFIX, RESULT_PREFIX)))
    requests = sum(1 for n in schemas if n.startswith(REQUEST_PREFIX))
    results = sum(1 for n in schemas if n.startswith(RESULT_PREFIX))
    out = [
        f"# {info['title']} Data Types",
        "",
        f"**Version:** {info['version']}",
        "",
        AGENT_NOTE,
        "",
        f"Model schemas: {len(models)}. Request ({REQUEST_PREFIX}*: {requests}) and result "
        f"({RESULT_PREFIX}*: {results}) wrapper schemas are listed per operation in `operations.md`.",
        "",
        "Classes ending in `C` hold constants (read them at runtime via `getConstants`).",
        "Classes ending in `Z` are element selectors that control which members are read or written.",
    ]
    for name in models:
        schema = schemas[name]
        out += ["", f"## `{name}`", ""]
        desc = clean(schema.get("description"))
        if desc:
            out += [desc, ""]
        props = dict(schema.get("properties", {}))
        for part in schema.get("allOf", []):
            if "$ref" in part:
                out += [f"Extends `{ref_name(part['$ref'])}`.", ""]
            props.update(part.get("properties", {}))
        if "enum" in schema:
            out += ["Values: " + ", ".join(f"`{v}`" for v in schema["enum"]), ""]
        if isinstance(schema.get("additionalProperties"), dict):
            out += [f"Type: `{type_of(schema)}`", ""]
        if schema.get("type") == "array":
            out += [f"Type: `{type_of(schema)}`", ""]
        if props:
            out += ["| Property | Type | Description |", "|----------|------|-------------|"]
            for prop in sorted(props):
                pschema = props[prop]
                pdesc = shorten(clean(pschema.get("description")), PROPERTY_DESC_LEN)
                out.append(f"| `{prop}` | {type_of(pschema)} | {pdesc} |")
        while out[-1] == "":
            out.pop()
    return "\n".join(out) + "\n"


def process(version_dir, check):
    spec = json.loads((version_dir / "openapi.json").read_text(encoding="utf-8"))
    targets = {
        version_dir / "generated" / "operations.md": render_operations(spec),
        version_dir / "generated" / "schemas.md": render_schemas(spec),
    }
    ok = True
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            print(f"outdated: {path.relative_to(ROOT)}")
            ok = False
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"written: {path.relative_to(ROOT)}")
    return ok


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version_dirs", nargs="*", type=Path)
    parser.add_argument("--check", action="store_true", help="fail if generated files are outdated")
    args = parser.parse_args()
    dirs = args.version_dirs or sorted(p for p in (ROOT / "api").iterdir() if (p / "openapi.json").exists())
    ok = all([process(d.resolve(), args.check) for d in dirs])
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
